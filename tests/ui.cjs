const {chromium}=require('playwright');
const path=require('node:path'),fs=require('node:fs'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.ICONO_BROWSER?{executablePath:process.env.ICONO_BROWSER}:{}),args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:900,height:930},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.resolve(__dirname,'../plugin/ui/index.html')).href);
 await page.waitForFunction(()=>window.IconoApp&&document.querySelectorAll('.icon-card').length===72);
 assert((await page.locator('#resultCount').textContent()).includes('5'));
 assert(await page.locator('#insert').isDisabled());
 await page.locator('#search').fill('ubicación');
 assert(await page.locator('.icon-card').count()>0);
 await page.locator('[data-id="tabler:map-pin"]').click();
 await page.locator('#variant').selectOption('solid');
 await page.locator('[data-preset="cutout"]').click();
 assert.equal(await page.locator('#previewIcon mask').count(),1);
 await page.locator('#bgMode').selectOption('gradient');
 await page.locator('#favorite').click();
 await page.waitForTimeout(300);
 await page.locator('#search').fill('');await page.locator('[data-filter="favorites"]').click();
 assert.equal(await page.locator('.icon-card').count(),1);
 await page.reload();await page.waitForFunction(()=>window.IconoApp);
 assert.equal(await page.locator('#selectedName').textContent(),'Map Pin');
 assert.equal(await page.locator('#iconMode').inputValue(),'cutout');
 assert.equal(await page.locator('#previewIcon mask').count(),1);
 await page.locator('[data-filter="brands"]').click();await page.locator('#search').fill('instagram');
 await page.locator('[data-id="brand:instagram"]').click();await page.locator('[data-preset="gradient"]').click();
 assert.equal(await page.locator('#color2Wrap').isVisible(),true);
 await page.locator('#size').fill('1024');
 const [svgDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#saveSVG').click()]);
 await svgDownload.saveAs(path.resolve(__dirname,'../qa/export-test.svg'));
 const svg=fs.readFileSync(path.resolve(__dirname,'../qa/export-test.svg'),'utf8');assert(svg.includes('width="1024"'));assert(svg.includes('<linearGradient'));
 const [pngDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#savePNG').click()]);
 await pngDownload.saveAs(path.resolve(__dirname,'../qa/export-test.png'));
 assert(fs.statSync(path.resolve(__dirname,'../qa/export-test.png')).size>1000);
 await page.locator('#search').fill('');await page.locator('[data-filter="all"]').click();await page.locator('[data-id="brand:whatsapp"]').click();await page.locator('[data-preset="circle"]').click();
 await page.locator('#size').fill('512');
 await page.screenshot({path:path.resolve(__dirname,'../qa/icono-panel-wide.png'),fullPage:true});
 for(const width of [390,330]){
  await page.setViewportSize({width,height:900});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'horizontal overflow at '+width);
  await page.locator('#shape').selectOption('rounded');await page.locator('#bgMode').selectOption('gradient');await page.locator('#border').check();
  assert(await page.locator('#borderControls').isVisible());
 }
 await page.setViewportSize({width:390,height:900});await page.screenshot({path:path.resolve(__dirname,'../qa/icono-panel-narrow.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 const runtime='Chromium '+browser.version()+'; browser UI only';
 await browser.close();
 console.log(JSON.stringify({ok:true,checks:['offline page loads','Spanish search','filled variant','transparent cutout','background gradient','favorites saved after reload','SVG download','PNG download','330px and 390px layout'],runtime},null,2));
})().catch(e=>{console.error(e);process.exit(1)});
